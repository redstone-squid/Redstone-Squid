import { functionName } from "./compile";
import { pseudoText } from "./pseudo";

/** `{locale: {group: {value: label}}}`, as written by scripts/export_vocabulary.py. */
export type Vocabulary = Record<string, Record<string, Record<string, string>>>;

// Each contract group's values are this OpenAPI type, so TypeScript rejects a missing label.
// Null marks a group keyed by plain strings, such as search field names, which data tags extend
// at runtime; its function returns undefined for a value it does not label.
const VALUE_TYPES: Record<string, string | null> = {
  record_criterion: "RecordCriterion",
  build_kind: "BuildKind",
  version_scope: "VersionScope",
  build_status: "BuildStatusFilter",
  record_fact: "RecordFact",
  search_build_kind: null,
  record_state: null,
  search_field: null,
  search_field_description: null,
};

/**
 * Compile the exported domain labels into one `<group>Label(value, locale?)` function per group.
 *
 * The first of `locales` is the source; every locale must label the same values. Each of
 * `pseudoLocales` gets the pseudo form of the source labels.
 */
export function compileVocabulary(
  vocabulary: Vocabulary,
  locales: readonly string[],
  pseudoLocales: readonly string[] = [],
): string {
  const source = locales[0];
  const english = source === undefined ? undefined : vocabulary[source];
  if (source === undefined || english === undefined)
    throw new Error(`The vocabulary has no labels for the source locale ${String(source)}.`);
  const groups = Object.keys(english);
  for (const locale of locales) {
    for (const group of groups) {
      const expected = Object.keys(english[group] ?? {}).toSorted();
      const actual = Object.keys(vocabulary[locale]?.[group] ?? {}).toSorted();
      if (JSON.stringify(expected) !== JSON.stringify(actual))
        throw new Error(`${locale}/${group} must label exactly: ${expected.join(", ")}`);
    }
  }
  const types = groups.map((group) => {
    const type = VALUE_TYPES[group];
    if (type === undefined)
      throw new Error(`Map vocabulary group ${group} to its OpenAPI type or null.`);
    return [group, type] as const;
  });
  const definitions = types.map(([group, type]) => {
    const name = functionName(group.replaceAll("_", "-"));
    const pseudoLabels = Object.fromEntries(
      Object.entries(english[group] ?? {}).map(([value, label]) => [value, pseudoText(label)]),
    );
    const labels = Object.fromEntries([
      ...locales.map((locale): [string, unknown] => [locale, vocabulary[locale]?.[group]]),
      ...pseudoLocales.map((locale): [string, unknown] => [locale, pseudoLabels]),
    ]);
    if (type === null)
      return [
        `const ${name}Labels: Record<Locale, Partial<Record<string, string>>> = ${JSON.stringify(labels)};`,
        `export function ${name}Label(value: string, locale: Locale = getLocale()): string | undefined {`,
        `  return ${name}Labels[locale][value];`,
        "}",
      ].join("\n");
    return [
      `const ${name}Labels = ${JSON.stringify(labels)} as const satisfies Record<Locale, Record<${type}, string>>;`,
      `export function ${name}Label(value: ${type}, locale: Locale = getLocale()): string {`,
      `  return ${name}Labels[locale][value];`,
      "}",
    ].join("\n");
  });
  const imported = types.flatMap(([, type]) => (type === null ? [] : [type])).toSorted();
  return [
    "// Generated by scripts/i18n/build.ts from contracts/vocabulary.json.",
    "// Edit squid/core/vocabulary.py and run `just export-vocabulary` instead.",
    ...(imported.length > 0
      ? [`import type { ${imported.join(", ")} } from "../generated/types.gen";`]
      : []),
    'import { getLocale, type Locale } from "./locale";',
    "",
    definitions.join("\n\n"),
    "",
  ].join("\n");
}
