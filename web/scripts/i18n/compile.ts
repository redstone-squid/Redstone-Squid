import { accent, padding } from "./pseudo";
import {
  parse,
  type Expression,
  type InlineExpression,
  type NamedArgument,
  type Pattern,
  type SelectExpression,
} from "@fluent/syntax";

/** How a variable is used, which decides its argument type and default formatting. */
type ArgumentKind = "text" | "number" | "date";
const KIND_RANK: Record<ArgumentKind, number> = { text: 0, number: 1, date: 2 };
const ARGUMENT_TYPES: Record<ArgumentKind, string> = {
  text: "string | number",
  number: "number",
  date: "Date | string",
};
const PLURAL_CATEGORIES = new Set(["zero", "one", "two", "few", "many", "other"]);

type Entry = { pattern: Pattern; term: boolean; source: string };
// A pseudo scope compiles the reference catalog with accented text.
type Scope = { locale: string; entries: Map<string, Entry>; pseudo: boolean };

/** Convert a Fluent ID such as `record-holder-count` to the exported `recordHolderCount`. */
export function functionName(id: string): string {
  return id.replaceAll(/-([a-z0-9])/g, (_match, letter: string) => letter.toUpperCase());
}

function parseCatalog(source: string, locale: string): Map<string, Entry> {
  const entries = new Map<string, Entry>();
  for (const entry of parse(source, {}).body) {
    if (entry.type !== "Message" && entry.type !== "Term") continue;
    if (entry.attributes.length > 0)
      throw new Error(`${locale}/${entry.id.name}: attributes are not supported yet.`);
    if (!entry.value) throw new Error(`${locale}/${entry.id.name}: empty message.`);
    const id = `${entry.type === "Term" ? "-" : ""}${entry.id.name}`;
    // The doc comment shows the English source with its whitespace collapsed.
    const span = entry.value.span;
    const text = span ? source.slice(span.start, span.end).replaceAll(/\s+/g, " ").trim() : id;
    entries.set(id, { pattern: entry.value, term: entry.type === "Term", source: text });
  }
  return entries;
}

/**
 * Compile Fluent catalogs into a TypeScript module with one function per message.
 *
 * Each function takes, when the message has variables, an `args` object whose types follow how
 * the variables are used: a plural selector or `NUMBER()` takes a number, `DATETIME()` takes a
 * date. The catalogs must already have matching IDs and variables. The first catalog is the
 * source; each of `pseudoLocales` gets an accented, bracketed, longer copy of it.
 */
export function compileCatalogs(
  catalogs: Record<string, string>,
  pseudoLocales: readonly string[] = [],
): string {
  const translated: Scope[] = Object.entries(catalogs).map(([locale, source]) => ({
    locale,
    entries: parseCatalog(source, locale),
    pseudo: false,
  }));
  const reference = translated[0];
  if (!reference) throw new Error("At least one catalog is required.");
  const scopes = [
    ...translated,
    ...pseudoLocales.map((locale) => ({ locale, entries: reference.entries, pseudo: true })),
  ];

  // Every locale contributes to a message's argument types, so translators can, for example,
  // add a plural selector that English does not need.
  const variablesOf = new Map<string, Map<string, ArgumentKind>>();
  for (const [id, entry] of reference.entries) {
    if (entry.term) continue;
    const variables = new Map<string, ArgumentKind>();
    for (const scope of scopes) collectKinds(scope, id, variables, []);
    variablesOf.set(id, variables);
  }

  const helpers = new Set<string>();
  const functions: string[] = [];
  const names = new Map<string, string>();
  for (const [id, variables] of variablesOf) {
    const name = functionName(id);
    const clash = names.get(name);
    if (clash !== undefined)
      throw new Error(`Messages ${clash} and ${id} both compile to ${name}.`);
    names.set(name, id);
    const parameters =
      variables.size === 0
        ? "locale: Locale = getLocale()"
        : `args: { ${[...variables]
            .toSorted(([a], [b]) => a.localeCompare(b, "en"))
            .map(([variable, kind]) => `${variable}: ${ARGUMENT_TYPES[kind]}`)
            .join("; ")} }, locale: Locale = getLocale()`;
    const cases = scopes.map((scope) => {
      const pattern = scope.entries.get(id)?.pattern;
      if (!pattern) throw new Error(`${scope.locale} is missing ${id}.`);
      const compiled = compilePattern(pattern, {
        scope,
        variables,
        variablesOf,
        helpers,
        argumentsOf: new Map(),
      });
      const body = scope.pseudo
        ? `"[" + ${compiled} + ${JSON.stringify(`${padding(textLength(pattern))}]`)}`
        : compiled;
      return `    case ${JSON.stringify(scope.locale)}:\n      return ${body};`;
    });
    const english = reference.entries.get(id)?.source ?? id;
    functions.push(
      `/** ${english.replaceAll("*/", "*\\/")} */\nexport function ${name}(${parameters}): string {\n  switch (locale) {\n${cases.join("\n")}\n  }\n}`,
    );
  }

  const imports = [...helpers].toSorted();
  return [
    "// Generated by scripts/i18n/build.ts from src/locales/*/messages.ftl. Edit the catalogs instead.",
    'import { getLocale, type Locale } from "./locale";',
    imports.length > 0 ? `import { ${imports.join(", ")} } from "./format";` : "",
    "",
    functions.join("\n\n"),
    "",
  ].join("\n");
}

/** Record the kind of every variable a message uses, following message and term references. */
function collectKinds(
  scope: Scope,
  id: string,
  variables: Map<string, ArgumentKind>,
  ancestors: string[],
): void {
  if (ancestors.includes(id))
    throw new Error(`Cyclic Fluent reference: ${[...ancestors, id].join(" -> ")}`);
  const entry = scope.entries.get(id);
  if (!entry) throw new Error(`${scope.locale}: unknown Fluent reference ${id}.`);
  const note = (name: string, kind: ArgumentKind) => {
    const current = variables.get(name);
    if (current === undefined || KIND_RANK[kind] > KIND_RANK[current]) variables.set(name, kind);
  };
  const visit = (node: Expression | Pattern, kind: ArgumentKind = "text"): void => {
    switch (node.type) {
      case "Pattern": {
        for (const element of node.elements)
          if (element.type === "Placeable") visit(element.expression);
        return;
      }
      case "Placeable": {
        visit(node.expression, kind);
        return;
      }
      case "VariableReference": {
        note(node.id.name, kind);
        return;
      }
      case "FunctionReference": {
        for (const argument of node.arguments.positional)
          visit(argument, node.id.name === "DATETIME" ? "date" : "number");
        return;
      }
      case "SelectExpression": {
        visit(node.selector, isPluralSelect(node) ? "number" : "text");
        for (const variant of node.variants) visit(variant.value);
        return;
      }
      case "MessageReference": {
        // Terms have their own argument scope; messages share the caller's variables.
        collectKinds(scope, node.id.name, variables, [...ancestors, id]);
        return;
      }
      case "TermReference": {
        for (const argument of node.arguments?.named ?? []) visit(argument.value);
        collectKinds(scope, `-${node.id.name}`, new Map(), [...ancestors, id]);
        return;
      }
      case "StringLiteral":
      case "NumberLiteral": {
        return;
      }
    }
  };
  visit(entry.pattern);
}

function isPluralSelect(node: SelectExpression): boolean {
  return node.variants.some(
    (variant) => variant.key.type === "NumberLiteral" || PLURAL_CATEGORIES.has(variant.key.name),
  );
}

type Context = {
  scope: Scope;
  variables: Map<string, ArgumentKind>;
  variablesOf: Map<string, Map<string, ArgumentKind>>;
  helpers: Set<string>;
  // Inside a term, its named arguments replace variables.
  argumentsOf: Map<string, string>;
};

function compilePattern(pattern: Pattern, context: Context): string {
  const parts = pattern.elements.map((element) =>
    element.type === "TextElement"
      ? JSON.stringify(context.scope.pseudo ? accent(element.value) : element.value)
      : compileExpression(element.expression, context),
  );
  return parts.length > 0 ? parts.join(" + ") : '""';
}

function compileExpression(node: Expression, context: Context): string {
  switch (node.type) {
    case "StringLiteral": {
      return JSON.stringify(node.parse().value);
    }
    case "NumberLiteral": {
      context.helpers.add("formatNumber");
      return `formatNumber(locale, ${node.value})`;
    }
    case "VariableReference": {
      return formatVariable(node.id.name, context);
    }
    case "Placeable": {
      return compileExpression(node.expression, context);
    }
    case "MessageReference": {
      if (node.attribute)
        throw new Error(`Attribute references are not supported: ${node.id.name}`);
      const takesArguments = (context.variablesOf.get(node.id.name)?.size ?? 0) > 0;
      return `${functionName(node.id.name)}(${takesArguments ? "args, " : ""}locale)`;
    }
    case "TermReference": {
      const term = context.scope.entries.get(`-${node.id.name}`);
      if (!term) throw new Error(`${context.scope.locale}: unknown term -${node.id.name}.`);
      const argumentsOf = new Map(
        (node.arguments?.named ?? []).map((argument) => [
          argument.name.name,
          compileExpression(argument.value, context),
        ]),
      );
      return `(${compilePattern(term.pattern, { ...context, argumentsOf })})`;
    }
    case "FunctionReference": {
      const [value] = node.arguments.positional;
      if (!value || (node.id.name !== "NUMBER" && node.id.name !== "DATETIME"))
        throw new Error(`Unsupported Fluent function: ${node.id.name}`);
      const helper = node.id.name === "NUMBER" ? "formatNumber" : "formatDateTime";
      context.helpers.add(helper);
      const options = compileOptions(node.arguments.named);
      return `${helper}(locale, ${rawValue(value, context)}${options !== "" ? `, ${options}` : ""})`;
    }
    case "SelectExpression": {
      context.helpers.add("select");
      const selector = node.selector;
      const value =
        selector.type === "FunctionReference" && selector.arguments.positional[0]
          ? rawValue(selector.arguments.positional[0], context)
          : rawValue(selector, context);
      const options =
        selector.type === "FunctionReference" ? compileOptions(selector.arguments.named) : "";
      const fallback = node.variants.find((variant) => variant.default);
      if (!fallback) throw new Error("A select expression needs a default variant.");
      const variants = node.variants
        .map(
          (variant) =>
            `${JSON.stringify(variant.key.type === "NumberLiteral" ? variant.key.value : variant.key.name)}: ${compilePattern(variant.value, context)}`,
        )
        .join(", ");
      const key = fallback.key.type === "NumberLiteral" ? fallback.key.value : fallback.key.name;
      return `select(locale, ${value}, { ${variants} }, ${JSON.stringify(key)}${options !== "" ? `, ${options}` : ""})`;
    }
  }
}

/** The unformatted value of a selector or function argument. */
function rawValue(node: InlineExpression, context: Context): string {
  if (node.type === "VariableReference")
    return context.argumentsOf.get(node.id.name) ?? `args.${node.id.name}`;
  if (node.type === "NumberLiteral") return node.value;
  if (node.type === "StringLiteral") return JSON.stringify(node.parse().value);
  throw new Error(`Unsupported selector or argument: ${node.type}`);
}

function formatVariable(name: string, context: Context): string {
  const bound = context.argumentsOf.get(name);
  if (bound !== undefined) return bound;
  const kind = context.variables.get(name) ?? "text";
  const helper = { text: "formatValue", number: "formatNumber", date: "formatDateTime" }[kind];
  context.helpers.add(helper);
  return `${helper}(locale, args.${name})`;
}

function compileOptions(named: NamedArgument[]): string {
  if (named.length === 0) return "";
  return `{ ${named
    .map(
      (argument) =>
        `${argument.name.name}: ${argument.value.type === "NumberLiteral" ? argument.value.value : JSON.stringify(argument.value.value)}`,
    )
    .join(", ")} }`;
}

/** The length of a pattern's own text, following each select expression's default variant. */
function textLength(pattern: Pattern): number {
  let length = 0;
  for (const element of pattern.elements) {
    if (element.type === "TextElement") length += element.value.length;
    else if (element.expression.type === "SelectExpression") {
      const fallback = element.expression.variants.find((variant) => variant.default);
      if (fallback) length += textLength(fallback.value);
    }
  }
  return length;
}
