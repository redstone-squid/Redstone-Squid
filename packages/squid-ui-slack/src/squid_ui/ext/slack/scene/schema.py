"""Wire schema declarations owned by the Slack target."""

from squid_ui.ext.slack.scene import model as m
from squid_ui.scene.schema import SceneSchema

SCHEMA = SceneSchema(
    tagged=(
        (m.SlackButton, "slack_button", "button"),
        (m.SlackSelect, "slack_select", "select"),
        (m.SlackTextInput, "slack_text_input", "text_input"),
        (m.SlackNumberInput, "slack_number_input", "number_input"),
        (m.SlackDatePicker, "slack_date_picker", "date_picker"),
        (m.SlackTimePicker, "slack_time_picker", "time_picker"),
        (m.SlackCheckboxes, "slack_checkboxes", "checkboxes"),
        (m.SlackRadioButtons, "slack_radio_buttons", "radio_buttons"),
        (m.SlackSection, "slack_section", "section"),
        (m.SlackHeader, "slack_header", "header"),
        (m.SlackContext, "slack_context", "context"),
        (m.SlackDivider, "slack_divider", "divider"),
        (m.SlackImage, "slack_image", "image"),
        (m.SlackActions, "slack_actions", "actions"),
        (m.SlackInput, "slack_input", "input"),
        (m.SlackTable, "slack_table", "table"),
        (m.SlackCard, "slack_card", "card"),
        (m.SlackCarousel, "slack_carousel", "carousel"),
        (m.SlackAlert, "slack_alert", "alert"),
        (m.SlackMessage, "slack_message", "slack_message"),
        (m.SlackModalView, "slack_modal", "slack_modal"),
        (m.SlackHomeView, "slack_home", "slack_home"),
    ),
    bodies=(m.SlackMessage, m.SlackModalView, m.SlackHomeView),
    plain=(
        ("slack_text", m.SlackText),
        ("slack_option", m.SlackOption),
        ("slack_action", m.SlackActionRef | None),
        ("slack_route", m.SlackRouteRef | None),
        ("slack_asset", m.SlackAssetRef | None),
    ),
    required={
        m.SlackText: ("content", "kind", "emoji", "verbatim"),
        m.SlackOption: ("label", "value", "description"),
        m.SlackActionRef: ("action", "mode"),
        m.SlackRouteRef: ("route_id",),
        m.SlackAssetRef: ("key", "name", "media_type"),
    },
    unions={
        "slack_element": (
            m.SlackButton,
            m.SlackSelect,
            m.SlackTextInput,
            m.SlackNumberInput,
            m.SlackDatePicker,
            m.SlackTimePicker,
            m.SlackCheckboxes,
            m.SlackRadioButtons,
        ),
        "slack_input_element": (
            m.SlackSelect,
            m.SlackTextInput,
            m.SlackNumberInput,
            m.SlackDatePicker,
            m.SlackTimePicker,
            m.SlackCheckboxes,
            m.SlackRadioButtons,
        ),
        "slack_block": (
            m.SlackSection,
            m.SlackHeader,
            m.SlackContext,
            m.SlackDivider,
            m.SlackImage,
            m.SlackActions,
            m.SlackInput,
            m.SlackTable,
            m.SlackCard,
            m.SlackCarousel,
            m.SlackAlert,
        ),
    },
    renames={m.SlackSelect: {"kind": "select_kind"}},
)
